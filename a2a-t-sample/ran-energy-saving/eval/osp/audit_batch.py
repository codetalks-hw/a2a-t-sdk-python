"""Grade every OSP case by what its artifacts prove, not by whether it passed.

The audit chain answers a different question from the pass rate: given what this run left behind,
can a third party say what was agreed and what was executed? A run can pass while proving nothing
(prose was accepted and prose was executed), and a run can be refused while proving everything.

This module runs the runnable cases of the OSP corpus through the real client flows against the
in-process NMS simulator and records, per run, the audit verdicts, the assurance grade of the
delegation chain, and the server-side request/round counters.

The Task-T is scripted from the case file rather than generated by a model. That is deliberate: the
question here is whether the *artifacts* bind, and a model's prose quality would add variance
without adding evidence about the protocol. Model-dependent pass rates are a different measurement
(`eval.osp.ai`).

Usage::

    PYTHONPATH=. python -m eval.osp.audit_batch
    PYTHONPATH=. python -m eval.osp.audit_batch --json /tmp/audit.json --protocols a2a-t,a2a
"""

