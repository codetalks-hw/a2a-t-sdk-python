CASES_DIR: Final[Path] = Path(__file__).resolve().parent / "cases"
A2A_BASE: Final[str] = "http://sim/a2a/json"
TOKEN_URL: Final[str] = "http://sim/rest/plat/smapp/v1/sessions"
USER: Final[str] = "snbitestDefaultNorth"
VALUE: Final[str] = "Changeme_123"
PROTOCOL_A2A_T: Final[str] = "a2a-t"
PROTOCOL_A2A: Final[str] = "a2a"
#: The A2A-T arm that also sends the typed statement, so both sides read the same data.
PROTOCOL_A2A_T_TYPED: Final[str] = "a2a-t-typed"
RUNNABLE_VALIDATION: Final[tuple[str, ...]] = ("pass", "pass_with_terminology")

#: The link names the audit reports, in order.
LINKS: Final[tuple[str, ...]] = (
    "request->accepted",
    "accepted->approval",
    "approval->execution",
    "change->baseline",
    "execution->restored",
)

_SEGMENT: Final[re.Pattern[str]] = re.compile(r"(\d+)Mbps[^.]*?(\d{1,2}):00\s*to\s*(\d{1,2}):00")


@dataclass
class CaseResult:
    """One (case, protocol) run and what its artifacts prove."""

    case_id: int
    name: str
    operation: str
    protocol: str
    final_state: str
    executed: bool
    links: dict[str, str] = field(default_factory=dict)
    matched: int = 0
    mismatched: int = 0
    unverifiable: int = 0
    not_applicable: int = 0
    weakest: str = ""
    violations: int = 0
    error: str = ""

    @property
    def decided(self) -> int:
        """Links a third party can decide, agree or disagree."""
        return self.matched + self.mismatched

    @property
    def full_chain(self) -> bool:
        """Every applicable link was decided; no link is left unverifiable."""
        return self.executed and self.unverifiable == 0 and self.decided > 0

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-friendly row."""
        return {
            "case": self.case_id,
            "name": self.name,
            "operation": self.operation,
            "protocol": self.protocol,
            "finalState": self.final_state,
            "executed": self.executed,
            "links": dict(self.links),
            "matched": self.matched,
            "mismatched": self.mismatched,
            "unverifiable": self.unverifiable,
            "notApplicable": self.not_applicable,
            "decided": self.decided,
            "fullChain": self.full_chain,
            "weakest": self.weakest,
            "violations": self.violations,
            "error": self.error,
        }


class _ScriptedPromptClient:
    """Return the case's expected Task-T instead of asking a model for one."""

    def __init__(self, task_t: str, fields: Mapping[str, object]) -> None:
        self._task_t = task_t
        self._fields = dict(fields)
        self.calls = 0

    def generate_task_prompt_from_text(self, text: str, template_uri: str) -> MetadataContent:
        self.calls += 1
        return MetadataContent(
            template_uri=template_uri,
            prompt_text=self._task_t,
            extension_uri=TASK_T_EXTENSION_URI,
        )

    def generate_task_prompt_from_data_with_schema(
        self,
        data: Mapping[str, object],
        schema: Mapping[str, object],
        template_uri: str,
    ) -> MetadataContent:
        del data, schema
        self.calls += 1
        return MetadataContent(
            template_uri=template_uri,
            prompt_text=self._task_t,
            extension_uri=TASK_T_EXTENSION_URI,
        )

    def generate_negotiation_accept_prompt_from_text(
        self, text: str | None, context: Any, template_uri: str
    ) -> MetadataContent:
        self.calls += 1
        return MetadataContent(
            template_uri=template_uri,
            prompt_text=text or "Accepted.",
            extension_uri="",
        )

    def generate_negotiation_accept_prompt_from_data(
        self, data: Any, template_uri: str
    ) -> MetadataContent:
        del data
        self.calls += 1
        return MetadataContent(
            template_uri=template_uri, prompt_text="Accepted.", extension_uri=""
        )

    def generate_negotiation_reject_prompt_from_text(
        self, text: str | None, context: Any, template_uri: str
    ) -> MetadataContent:
        return self.generate_negotiation_accept_prompt_from_text(text, context, template_uri)

    def generate_negotiation_propose_prompt_from_text(
        self, text: str | None, context: Any, template_uri: str
    ) -> MetadataContent:
        return self.generate_negotiation_accept_prompt_from_text(text, context, template_uri)

    def validate_task_prompt_and_data_filling(
        self,
        prompt: str,
        schema: Mapping[str, object],
        template_uri: str,
    ) -> object:
        del prompt, schema, template_uri
        return dict(self._fields)


def _sim_config() -> SimConfig:
    """The switch profile this batch runs under; it is recorded in the report header."""
    return SimConfig(
        fidelity=FIDELITY_FAST,
        window_policy=WINDOW_POLICY_ANY,
        rate_policy=RATE_POLICY_OPTIONAL,
        approval=True,
    )


def _runnable_cases() -> list[dict[str, Any]]:
    cases: list[dict[str, Any]] = []
    for path in sorted(CASES_DIR.glob("*.yaml")):
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(document, Mapping):
            continue
        expect = document.get("expect") or {}
        protocols = (expect.get("protocols") or {}).get(PROTOCOL_A2A_T) or {}
        if protocols.get("validate") not in RUNNABLE_VALIDATION:
            continue
        cases.append(dict(document))
    return cases


def _case_task_t(case: Mapping[str, Any]) -> str:
    protocols = (case.get("expect") or {}).get("protocols") or {}
    block = protocols.get(PROTOCOL_A2A_T) or {}
    return str(block.get("task_t") or "")


def _intent_fields(case: Mapping[str, Any]) -> dict[str, object]:
    """Project the case's expected intent onto the three Task-T parameters a plan needs.

    The OSP intent is the oracle the tester compares against; here it stands in for the intent
    agent's output, which is what supplies these fields in a real run. Deriving them from the Task-T
    prose instead would measure the SDK's prose reconstruction, which is a different question.
    """
    intent = (case.get("expect") or {}).get("intent") or {}
    fields: dict[str, object] = {
        "operationType": str(intent.get("Operation type") or case.get("operation") or ""),
        "region": str(intent.get("Energy saving region") or ""),
    }
    zones = intent.get("Guaranteed throughput target by zone") or []
    targets: list[str] = []
    for zone in zones:
        if not isinstance(zone, Mapping):
            continue
        rate = str(zone.get("Guaranteed throughput target") or "").replace(" ", "")
        periods = str(zone.get("Effective time period") or "").split("&")
        first, last = periods[0], periods[-1]
        if "-" not in first or "-" not in last or not rate:
            continue
        # The OSP periods end at HH:59:59, and the simulator plans in whole hours: the window
        # closes at the next hour boundary.
        start = first.split("-")[0][:2] + ":00"
        end = f"{int(last.split('-')[1].split(':')[0]) + 1:02d}:00"
        targets.append(f"{{{start}-{end},{rate}}}")
    if targets:
        fields["guaranteedThroughputTarget"] = ", ".join(targets)
    return fields


_TARGET: Final[re.Pattern[str]] = re.compile(r"\{[0-9:]+-[0-9:]+,\s*[0-9.]+\s*Mbps\}")
_OPERATION: Final[re.Pattern[str]] = re.compile(r"## Operation Type\s*\n+\s*(\w+)")
_REGION: Final[re.Pattern[str]] = re.compile(r"## Task Object\s*\n+\s*([A-Za-z0-9_]+)")


def _task_t_fields(task_t: str) -> dict[str, object]:
    """Read the three plan parameters out of the rendered Task-T, as a client could.

    This is deliberately no smarter than the document: whatever the prose does not state, the client
    cannot know, and the difference between this projection and the server's reading is exactly what
    the audit measures.
    """
    operation = _OPERATION.search(task_t)
    region = _REGION.search(task_t)
    targets = _TARGET.findall(task_t)
    fields: dict[str, object] = {
        "operationType": operation.group(1) if operation else "Create",
        "region": region.group(1) if region else "",
    }
    if targets:
        fields["guaranteedThroughputTarget"] = ", ".join(targets)
    return fields


def _baseline_task_t(text: str) -> str:
    """Build a deterministic Create Task-T for a Modify case's paired baseline.

    The baseline exists so the Modify has something to target; its own wording is not under test,
    so a rendered document built from the case's stated segments is enough and keeps the batch
    free of a model call.
    """
    region = re.search(r"for\s+([A-Za-z0-9]+)\s+region", text, re.I)
    segments = [
        f"{{{start}:00-{end}:00,{rate}Mbps}}"
        for rate, start, end in _SEGMENT.findall(text)
    ]
    target = ", ".join(segments) or "{00:00-06:00,10Mbps}"
    return "\n".join(
        [
            "## Operation Type",
            "",
            "Create",
            "",
            "## Task Object",
            "",
            f"The area is {region.group(1) if region else 'A2ATestRegion'}.",
            "",
            "## Task Context",
            "",
            f"The time-segment-based guaranteed throughput target is {target}.",
        ]
    )


async def _token(http: httpx.AsyncClient) -> str:
    response = await http.put(
        TOKEN_URL.removeprefix("http://sim"),
        json={"grantType": "password", "userName": USER, "value": VALUE},
    )
    response.raise_for_status()
    return str(response.json()["accessSession"])


async def _create_baseline(
    http: httpx.AsyncClient, token: str, text: str
) -> tuple[str, str]:
    response = await http.post(
        "/a2a/json/message:send",
        json={
            "message": {
                "messageId": "baseline-1",
                "role": "ROLE_USER",
                "parts": [{"text": "run"}],
                "metadata": {TASK_T_EXTENSION_URI: _baseline_task_t(text)},
            }
        },
        headers={"Authorization": f"Bearer {token}", "A2A-Extensions": TASK_T_EXTENSION_URI},
    )
    response.raise_for_status()
    document = response.json()
    if "task" in document:
        task = document["task"]
        return str(task["id"]), str(task.get("contextId") or "")
    raise RuntimeError(f"the baseline did not create a task: {str(document)[:200]}")


def _audit_row(
    case: Mapping[str, Any], protocol: str, result: ClientFlowResult
) -> CaseResult:
    audit = result.audit or {}
    links = {str(link.get("name")): str(link.get("status")) for link in audit.get("links", [])}
    summary = audit.get("summary") or {}
    readback = result.readback or {}
    delegation = readback.get("delegation") if isinstance(readback, Mapping) else None
    weakest = ""
    violations = 0
    if isinstance(delegation, list) and delegation:
        from shared.assurance import read_hops, report

        hops = read_hops({"version": 2, "hops": delegation})
        graded = report(hops)
        weakest = graded.weakest
        violations = len(graded.violations)
    row = CaseResult(
        case_id=int(case["id"]),
        name=str(case["name"]),
        operation=str(case["operation"]),
        protocol=protocol,
        final_state=result.final_state,
        executed=result.final_state == FINAL_STATE_TASK_COMPLETED,
        links={name: links.get(name, "absent") for name in LINKS},
        matched=int(summary.get("matched", 0)),
        mismatched=int(summary.get("mismatched", 0)),
        unverifiable=int(summary.get("unverifiable", 0)),
        not_applicable=int(summary.get("notApplicable", 0)),
        weakest=weakest,
        violations=violations,
        error=result.error or "",
    )
    return row


async def _run_a2a_t(
    case: Mapping[str, Any],
    http: httpx.AsyncClient,
    *,
    task_id: str | None,
    context_id: str | None,
    typed: bool = False,
) -> CaseResult:
    nms = NmsClient(
        NmsConfig(
            a2a_base=A2A_BASE,
            token_url=TOKEN_URL,
            token_user=USER,
            token_value=VALUE,
            wire_log=False,
            # The simulator finishes in milliseconds under ``fidelity=fast``; the defaults wait two
            # minutes for a stream the server keeps open, which would dominate the batch.
            idle_timeout=5.0,
            send_timeout=20.0,
            poll_interval=0.2,
            poll_after_silence=5.0,
            # The flow answers INPUT_REQUIRED itself and sends again; waiting for a terminal state
            # on the first message would spend the whole read budget on a Task that is waiting for
            # the client.
            defer_to_tracker=True,
        ),
        http_client=http,
    )
    task_t = _case_task_t(case)
    # A text run can only know what its own document says; a typed run carries the values as data,
    # which is the difference this arm exists to measure.
    fields = _intent_fields(case) if typed else _task_t_fields(task_t)
    prompt = _ScriptedPromptClient(task_t, fields)
    result = await run_client_flow(
        prompt_client=prompt,
        transport=NmsSseTransport(nms, request_timeout=20.0),
        user_request=str(case.get("user_input") or ""),
        provider=ScriptedDecisionProvider(
            [NegotiationDecision(action="accept", rationale="scripted accept")]
        ),
        language="en-US",
        approval_answer=approval_answer(),
        approval_plan=plan_from_task_t,
        call_timeout_seconds=30.0,
        intent_fields=fields,
        typed_statement=typed_statement_from_task_t if typed else None,
        run_mode=RUN_MODE_MODIFY if task_id else RUN_MODE_CREATE,
        target_task_id=task_id,
        target_context_id=context_id,
    )
    return _audit_row(case, PROTOCOL_A2A_T_TYPED if typed else PROTOCOL_A2A_T, result)


async def _run_pure(case: Mapping[str, Any], http: httpx.AsyncClient) -> CaseResult:
    nms = NmsClient(
        NmsConfig(
            a2a_base=A2A_BASE,
            token_url=TOKEN_URL,
            token_user=USER,
            token_value=VALUE,
            wire_log=False,
            # The simulator finishes in milliseconds under ``fidelity=fast``; the defaults wait two
            # minutes for a stream the server keeps open, which would dominate the batch.
            idle_timeout=5.0,
            send_timeout=20.0,
            poll_interval=0.2,
            poll_after_silence=5.0,
            # The flow answers INPUT_REQUIRED itself and sends again; waiting for a terminal state
            # on the first message would spend the whole read budget on a Task that is waiting for
            # the client.
            defer_to_tracker=True,
        ),
        http_client=http,
    )
    result = await run_pure_client_flow(
        transport=NmsSseTransport(nms, request_timeout=20.0),
        user_request=str(case.get("user_input") or ""),
        max_rounds=3,
    )
    return _audit_row(case, PROTOCOL_A2A, result)


async def run_batch(protocols: Sequence[str]) -> list[CaseResult]:
    """Run every runnable case for each protocol and return one row per (case, protocol)."""
    rows: list[CaseResult] = []
    cases = _runnable_cases()
    for case in cases:
        ran_data.reset()
        app = build_sim_app(_sim_config())
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://sim"
        ) as http:
            token = await _token(http)
            task_id: str | None = None
            context_id: str | None = None
            baseline = (case.get("baseline") or {}).get("request")
            if case.get("operation") == "Modify" and isinstance(baseline, str):
                try:
                    task_id, context_id = await _create_baseline(http, token, baseline)
                except Exception as exc:  # noqa: BLE001 - a case that cannot be prepared is a row
                    task_id = None
                    _ = exc
            for protocol in protocols:
                if protocol in (PROTOCOL_A2A_T, PROTOCOL_A2A_T_TYPED):
                    try:
                        rows.append(
                            await _run_a2a_t(
                                case,
                                http,
                                task_id=task_id,
                                context_id=context_id,
                                typed=protocol == PROTOCOL_A2A_T_TYPED,
                            )
                        )
                    except Exception as exc:  # noqa: BLE001 - one case must not end the batch
                        rows.append(_failed(case, protocol, exc))
                else:
                    try:
                        rows.append(await _run_pure(case, http))
                    except Exception as exc:  # noqa: BLE001
                        rows.append(_failed(case, protocol, exc))
    return rows


def _failed(case: Mapping[str, Any], protocol: str, exc: Exception) -> CaseResult:
    return CaseResult(
        case_id=int(case["id"]),
        name=str(case["name"]),
        operation=str(case["operation"]),
        protocol=protocol,
        final_state="error",
        executed=False,
        links={name: "absent" for name in LINKS},
        error=f"{type(exc).__name__}: {exc}"[:300],
    )


def summarize(rows: Sequence[CaseResult]) -> dict[str, object]:
    """Return the per-protocol counts a report quotes."""
    out: dict[str, object] = {}
    for protocol in (PROTOCOL_A2A_T, PROTOCOL_A2A_T_TYPED, PROTOCOL_A2A):
        subset = [row for row in rows if row.protocol == protocol]
        if not subset:
            continue
        out[protocol] = {
            "cases": len(subset),
            "executed": sum(1 for row in subset if row.executed),
            "fullChain": sum(1 for row in subset if row.full_chain),
            "decidedLinks": sum(row.decided for row in subset),
            "unverifiableLinks": sum(row.unverifiable for row in subset),
            "mismatchedLinks": sum(row.mismatched for row in subset),
            "violations": sum(row.violations for row in subset),
            "errors": sum(1 for row in subset if row.error),
            "weakest": _count(row.weakest for row in subset if row.weakest),
        }
    return out


def _count(values: Any) -> dict[str, int]:
    counts: dict[str, int] = {}
    for value in values:
        counts[str(value)] = counts.get(str(value), 0) + 1
    return counts


def _markdown(rows: Sequence[CaseResult], summary: Mapping[str, Any]) -> str:
    lines = ["| case | op | protocol | state | " + " | ".join(LINKS) + " | full |",
             "|---:|---|---|---|" + "---|" * len(LINKS) + "---|"]
    for row in rows:
        cells = [str(row.case_id), row.operation, row.protocol, row.final_state]
        cells += [row.links.get(name, "absent") for name in LINKS]
        cells.append("yes" if row.full_chain else "no")
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    for protocol, counts in summary.items():
        if isinstance(counts, dict):
            lines.append(f"- {protocol}: {counts}")
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=Path, default=None)
    parser.add_argument(
        "--protocols", default=f"{PROTOCOL_A2A_T},{PROTOCOL_A2A_T_TYPED},{PROTOCOL_A2A}"
    )
    args = parser.parse_args(argv)
    protocols = tuple(part.strip() for part in str(args.protocols).split(",") if part.strip())
    rows = asyncio.run(run_batch(protocols))
    summary = summarize(rows)
    print(_markdown(rows, summary))
    if args.json:
        args.json.write_text(
            json.dumps(
                {
                    "settings": {
                        "fidelity": FIDELITY_FAST,
                        "windowPolicy": WINDOW_POLICY_ANY,
                        "ratePolicy": RATE_POLICY_OPTIONAL,
                        "approval": True,
                        "taskT": "scripted from the case file",
                    },
                    "summary": summary,
                    "rows": [row.to_dict() for row in rows],
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
